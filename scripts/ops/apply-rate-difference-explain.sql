-- v2.5 (2026-08-14 คำสั่งเจ้าของ): เสนอ 2 เรทแล้วต้องบอกด้วยว่าต่างกันยังไง
-- ความต่างที่ลูกค้าต้องรู้ = เอกสารที่ใช้ (+ จำนวนงวดสูงสุดถ้าต่างกัน) — ยังห้ามเอ่ยชื่อร้าน/ไฟแนนซ์
BEGIN;

UPDATE system_config
SET value = replace(value,
$OLD$วิธีเสนอ: ได้ผลจาก get_installment_rates ให้เสนอทั้ง 2 เรทคู่กัน (ดาวน์/เดือนละ/กี่เดือน)
เช่น "เรทที่ 1 ดาวน์ 1,900 ผ่อนเดือนละ 2,566 บาท 12 งวด
     เรทที่ 2 ดาวน์ 3,400 ผ่อนเดือนละ 2,905 บาท 12 งวด สนใจเรทไหนดีคะ"
แล้วให้ลูกค้าเลือก — ตัวเลขห้ามมาจากที่อื่นนอกจาก tool$OLD$,
$NEW$วิธีเสนอ: ได้ผลจาก get_installment_rates ให้เสนอทั้ง 2 เรทคู่กัน (ดาวน์/เดือนละ/กี่เดือน)
**พร้อมบอกสั้น ๆ เสมอว่าสองเรทต่างกันยังไง** — ความต่างที่ลูกค้าต้องรู้คือ
เอกสารที่ใช้ (และจำนวนงวดสูงสุด ถ้ารุ่นนั้นสองเรทให้งวดไม่เท่ากัน)
เช่น "เรทที่ 1 ดาวน์ 1,900 ผ่อนเดือนละ 2,566 บาท 12 งวด
     เรทที่ 2 ดาวน์ 3,400 ผ่อนเดือนละ 2,905 บาท 12 งวด
     สองเรทต่างกันที่เอกสารค่ะ เรทที่ 1 ใช้สเตทเม้นท์ย้อนหลัง 3 เดือน เรทที่ 2 ใช้แค่รูปตอนทำงาน
     สนใจเรทไหนดีคะ"
ลูกค้าถาม "ต่างกันยังไง" → ตอบเรื่องเอกสาร + จำนวนงวดสูงสุด (ห้ามเอ่ยชื่อร้าน/ไฟแนนซ์เหมือนเดิม)
แล้วให้ลูกค้าเลือก — ตัวเลขห้ามมาจากที่อื่นนอกจาก tool$NEW$),
    updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

COMMIT;

SELECT
  CASE WHEN value LIKE '%สองเรทต่างกันที่เอกสารค่ะ%' THEN '✓ บอกความต่างพร้อมเรท' ELSE '✗ ไม่ติด' END,
  length(value) AS len
FROM system_config WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;
