import assert from 'node:assert/strict';
import { chromium, expect } from '@playwright/test';

const origin = process.env.CREDIT_PREVIEW_ORIGIN || 'http://localhost:5187';
const response = await fetch(`${origin}/api/admin/preview/info`);
assert.equal(response.status, 200, 'Start tools/preview-chat-credit.sh before running this check');
const info = await response.json();
assert.equal(info.isolated, true);
assert.equal(info.ocr, 'mock', 'This browser check uses fixed synthetic OCR, never real customer data');
assert.equal(info.storage, 'local-files', 'This browser check requires local-files storage');
const fixtureResponse = await fetch(`${origin}/api/admin/preview/fixture`, { method: 'POST' });
assert.equal(fixtureResponse.status, 201);
const fixture = await fixtureResponse.json();
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1500, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(`${origin}/inbox/${fixture.roomId}`);
  await expect(page.getByRole('heading', { name: 'ตรวจเครดิต', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'แนบเพื่อตรวจเครดิต', exact: true }).click();
  await page.getByRole('button', { name: 'AI วิเคราะห์ (1 ไฟล์)', exact: true }).click();
  await expect(page.getByText('6,000 บาท', { exact: true })).toBeVisible({ timeout: 10000 });
  await page.getByRole('button', { name: 'ค้นหาลูกค้าเดิม', exact: true }).click();
  await page.getByRole('textbox', { name: 'ค้นหาลูกค้า' }).fill(fixture.customerName);
  await page.getByRole('button', { name: new RegExp(fixture.customerName) }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.getByRole('button', { name: 'ดูรายละเอียด', exact: true }).click();
  await page.getByRole('link', { name: 'เปิดประวัติตรวจเครดิตของลูกค้า' }).click();
  await expect(page.getByRole('tab', { name: /เครดิต/ })).toHaveAttribute('data-state', 'active');
  await expect(page.getByRole('button', { name: 'ปรับแก้สถานะ', exact: true })).toBeVisible();
  await expect(page.getByText(/ผ่อนไหวเดือนละ.*6,000/)).toBeVisible();
  await page.screenshot({ path: 'docs/review/2026-09-07-chat-credit-customer-history.png', fullPage: true });
  let customer = await (await fetch(`${origin}/api/admin/customers/${fixture.customerId}`)).json();
  assert.equal(customer.creditCheckStatus, 'UNDER_REVIEW');

  await page.goto(`${origin}/credit-checks`);
  const row = page.getByRole('row').filter({ hasText: fixture.customerName });
  await row.getByRole('button', { name: 'อนุมัติ', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel(/รายได้ประจำที่ยืนยัน/).fill('15000');
  await dialog.getByLabel(/ค่าครองชีพ/).fill('9000');
  await dialog.getByLabel(/ค่างวดหนี้ภายนอก/).fill('0');
  await dialog.getByLabel('วันเงินเดือนออก / วันครบกำหนดชำระ').selectOption('31');
  await dialog.getByLabel(/หลักฐานและที่มาของตัวเลข/).fill('ตรวจสอบเอกสารสังเคราะห์ รายได้ รายจ่าย หนี้ และวันรับเงินครบถ้วน');
  await dialog.getByRole('button', { name: 'คำนวณเพดาน', exact: true }).click();
  await expect(dialog.getByText('เพดานที่คำนวณ: 3,000 บาท/เดือน')).toBeVisible();
  await dialog.getByLabel('อนุมัติค่างวดไม่เกิน (บาท/เดือน)').fill('1500');
  await dialog.getByRole('checkbox').check();
  await dialog.getByLabel(/เหตุผล \(อย่างน้อย/).fill('ตรวจสอบเอกสารสังเคราะห์และตัวเลขครบถ้วนสำหรับทดสอบ local');
  await dialog.getByRole('button', { name: /ยืนยัน/ }).click();
  await expect(dialog).not.toBeVisible();
  await expect(row).not.toBeVisible();
  customer = await (await fetch(`${origin}/api/admin/customers/${fixture.customerId}`)).json();
  assert.equal(customer.creditCheckStatus, 'FULL_CHECK_PASSED');
  const history = await (await fetch(`${origin}/api/admin/customers/${fixture.customerId}/credit-check`)).json();
  assert.equal(history[0].status, 'APPROVED');
  assert.equal(history[0].aiScore, null);
  assert.equal(Number(history[0].approvals[0].approvedMonthlyPayment), 1500);
  assert.equal(history[0].approvals[0].salaryPayDay, 31);
  assert.equal(history[0].aiAnalysis.affordablePayment, 6000);
  const file = await fetch(`${origin}/api/admin${history[0].statementFiles[0]}`);
  assert.equal(file.status, 200);
  assert.equal(Buffer.from(await file.arrayBuffer()).subarray(0, 5).toString(), '%PDF-');
  await page.goto(`${origin}/contracts/create?customerId=${fixture.customerId}&productId=${fixture.productId}`);
  await page.getByRole('button', { name: 'ถัดไป', exact: true }).click();
  await page.getByRole('button', { name: 'ถัดไป', exact: true }).click();
  await expect(page.getByText('ยอดที่ผู้จัดการอนุมัติ: ไม่เกิน 1,500 บาท/เดือน')).toBeVisible();
  const payday = page.getByLabel('วันที่ครบกำหนดชำระ (ตามวันเงินเดือนออก)');
  await expect(payday).toHaveValue('31');
  await payday.selectOption('25');
  await expect(page.getByText('วันชำระต้องตรงกับวันเงินเดือนในผลอนุมัติ')).toBeVisible();
  await expect(page.getByRole('button', { name: 'สร้างสัญญา', exact: true })).toBeDisabled();
  await payday.selectOption('31');
  await expect(page.getByText('ค่างวดเกินยอดอนุมัติ กรุณาปรับเงินดาวน์หรือแผนผ่อน')).toBeVisible();
  await page.getByRole('spinbutton').fill('5000');
  await page.getByLabel('จำนวนงวด (เดือน)').selectOption('12');
  await expect(page.getByRole('button', { name: 'สร้างสัญญา', exact: true })).toBeEnabled();
  await page.screenshot({ path: 'docs/review/2026-09-08-credit-approved-plan.png', fullPage: true });
  const responsePromise = page.waitForResponse(response => response.url().endsWith('/contracts') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'สร้างสัญญา', exact: true }).click();
  const createdResponse = await responsePromise;
  const created = await createdResponse.json();
  assert.equal(createdResponse.status(), 201, JSON.stringify(created));
  assert.equal(created.payments.length, 12);
  assert.ok(created.payments.every(payment => Number(payment.amountDue) <= 1500));
  for (const payment of created.payments) {
    const due = new Date(payment.dueDate);
    assert.equal(due.getDate(), new Date(due.getFullYear(), due.getMonth() + 1, 0).getDate());
  }
  const used = await (await fetch(`${origin}/api/admin/customers/${fixture.customerId}/credit-check/latest`)).json();
  assert.equal(used.approvals[0].usedByContractId, created.id);
  assert.equal(new Date(used.approvals[0].usedFirstPaymentDue).getTime(), new Date(created.payments[0].dueDate).getTime());
  assert.deepEqual(errors, []);
  console.log('PASS: attach → analyze → link customer → credit history → manager approval → persisted amount/payday → contract plan guard → real contract and 12 month-end installments');
} finally {
  await browser.close();
}
