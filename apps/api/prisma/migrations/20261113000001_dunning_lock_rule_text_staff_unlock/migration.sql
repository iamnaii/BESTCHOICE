-- ⇒ "… แล้วเจ้าหน้าที่จะปลดล็อคให้" · แก้เฉพาะแถวที่ยังเป็นข้อความ seed เดิมทุกตัวอักษร (ข้อความที่เจ้าของแก้แล้วไม่แตะ)
-- idempotent: รันซ้ำไม่มีแถวตรงเงื่อนไข
UPDATE "dunning_rules"
SET "message_template" = 'เครื่องของท่านถูกล็อคและตั้ง wallpaper แจ้งเตือน กรุณาชำระยอดค้าง {{amount}} ฿ แล้วเจ้าหน้าที่จะปลดล็อคให้',
    "updated_at" = NOW()
WHERE "event_trigger" = 'DEVICE_LOCKED'
  AND "message_template" = 'เครื่องของท่านถูกล็อคและตั้ง wallpaper แจ้งเตือน กรุณาชำระยอดค้าง {{amount}} ฿ เพื่อปลดล็อคทันที';
