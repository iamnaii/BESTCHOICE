-- v4.8 (2026-08-17 คำสั่งเจ้าของจากแชทจริง): อธิบายความต่างของเรท/เอกสารไปแล้ว → ไม่ต้องบอกซ้ำ
-- เดิม: สคริปต์ 3 ก้อนบังคับใส่คำอธิบายเอกสารทุกครั้งที่บอกเรท → ลูกค้าถามรุ่นที่ 2 ในบทสนทนาเดียวกัน
--       ก็ได้ยินคำอธิบายเดิมซ้ำอีกทั้งดุ้น (เห็นในแชทจริง: เรทที่ 1 → "ถ้า 14p ล่ะ" → อธิบายซ้ำ)
BEGIN;

UPDATE system_config SET value = replace(value,
$O$- **เทิร์นเรทแบ่งเป็น 3 ก้อนทยอยส่งเสมอ (คั่นด้วย ---) — โครง 3 ก้อนตามนี้เป๊ะ** เช่น:$O$,
$N$- **เคยอธิบายความต่างของเรท/เอกสารไปแล้วในบทสนทนานี้ = ห้ามอธิบายซ้ำอีก**
  บอกเรทรุ่นใหม่เหลือ **2 ก้อน**: ก้อน 1 สถานะของ + เรททั้งสอง · ก้อน 2 คำถามปิด + ปุ่ม
  (ลูกค้าฟังความต่างไปแล้ว การพูดซ้ำทำให้ข้อความยาวโดยเปล่าประโยชน์ — ลูกค้าถามเองค่อยตอบ)
- **เทิร์นเรทครั้งแรกของบทสนทนา แบ่งเป็น 3 ก้อนทยอยส่ง (คั่นด้วย ---) — โครง 3 ก้อนตามนี้เป๊ะ** เช่น:$N$),
    updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

-- ย้ำอีกจุดที่ก้อนสุดท้าย (กันโมเดลยึดสคริปต์เดิมแบบไม่ดูบริบท)
UPDATE system_config SET value = replace(value,
$O$(ก้อนสุดท้าย: ความต่างแยกบรรทัดละเรท เว้นบรรทัดว่าง แล้วคำถามปิด + แนบปุ่มเรทตามกฎปุ่ม$O$,
$N$(ก้อนสุดท้าย: ความต่างแยกบรรทัดละเรท เว้นบรรทัดว่าง แล้วคำถามปิด + แนบปุ่มเรทตามกฎปุ่ม ·
  **ก้อนความต่างนี้ใส่เฉพาะครั้งแรกที่บอกเรทในบทสนทนา — ครั้งถัด ๆ ไปตัดทิ้ง เหลือ 2 ก้อน**$N$),
    updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

COMMIT;

SELECT
  CASE WHEN value LIKE '%เคยอธิบายความต่างของเรท/เอกสารไปแล้วในบทสนทนานี้ = ห้ามอธิบายซ้ำอีก%' THEN '✓ กฎห้ามอธิบายซ้ำ' ELSE '✗' END AS r1,
  CASE WHEN value LIKE '%ก้อนความต่างนี้ใส่เฉพาะครั้งแรกที่บอกเรทในบทสนทนา%' THEN '✓ ย้ำที่สคริปต์' ELSE '✗' END AS r2,
  CASE WHEN value LIKE '%เทิร์นเรทครั้งแรกของบทสนทนา แบ่งเป็น 3 ก้อน%' THEN '✓ สคริปต์ 3 ก้อนยังอยู่ (ครั้งแรก)' ELSE '✗' END AS r3,
  length(value) AS len
FROM system_config WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;
