-- v2.8 (2026-08-14 คำสั่งเจ้าของ): รุ่นนอกรายการมือ 1 ต้องบอกเหตุผลด้วยเสมอ
-- "รุ่นนี้มือ 1 ไม่มีผลิตแล้ว มีแต่มือ 2" — ลูกค้าเข้าใจว่าเป็นเรื่องโรงงานเลิกผลิต ไม่ใช่ร้านไม่มีของ
-- (ใช้ "จะเป็นเครื่องมือสอง..." ไม่ใช้ "มีเป็น..." — กันชนกฎห้าม "มีของ" คู่ "กำลังเข้ามา")
BEGIN;

-- [1] กฎเหล็กข้อมูลสินค้า (โหมดรับออเดอร์)
UPDATE system_config
SET value = replace(value,
$OLD$  รุ่นนอกรายการ = สั่งได้เฉพาะมือสอง → บอกประเภทว่า "รุ่นนี้เป็นเครื่องมือสองคัดสภาพนะคะ" ห้ามถามมือ 1**$OLD$,
$NEW$  รุ่นนอกรายการ = สั่งได้เฉพาะมือสอง → **บอกเหตุผลให้ลูกค้าเข้าใจด้วยเสมอ**:
  "รุ่นนี้มือ 1 ไม่มีผลิตแล้วนะคะ จะเป็นเครื่องมือสองคัดสภาพค่า" ห้ามถามมือ 1**$NEW$),
    updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

-- [2] รายการมือ 1 (กติการุ่นนอกรายการ)
UPDATE system_config
SET value = replace(value,
$OLD$  → บอกประเภท "รุ่นนี้เป็นเครื่องมือสองคัดสภาพค่า" — สต๊อกว่างก็บอกตรง ๆ ต่อว่า$OLD$,
$NEW$  → บอกเหตุผลด้วยเสมอ: "รุ่นนี้มือ 1 ไม่มีผลิตแล้วนะคะ จะเป็นเครื่องมือสองคัดสภาพค่า"
  — สต๊อกว่างก็บอกตรง ๆ ต่อว่า$NEW$),
    updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

COMMIT;

-- ตรวจผล: ต้อง ✓ ทั้ง 2 (วลีปรากฏ 2 จุด)
SELECT
  CASE WHEN (length(value) - length(replace(value, 'มือ 1 ไม่มีผลิตแล้วนะคะ', ''))) / length('มือ 1 ไม่มีผลิตแล้วนะคะ') = 2
       THEN '✓ วลีครบ 2 จุด' ELSE '✗' END,
  length(value) AS len
FROM system_config WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;
