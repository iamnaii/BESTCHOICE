-- v3.2 (2026-08-15): ลูกค้าขอเทียบรุ่น ("ต่างกันยังไง/เอาตัวไหนดี") → เทียบด้วยตัวเลขจริงเสมอ
-- เทสจริง: บอทเทียบลอย ๆ "ดาวน์เบากว่า/ถูกกว่า" ไม่มีเลข — ขัดหลัก "ลูกค้าคิดเป็นดาวน์+งวด"
BEGIN;

UPDATE system_config
SET value = replace(value,
$OLD$## กรณีอื่น$OLD$,
$NEW$## ลูกค้าขอเทียบรุ่น ("ต่างกันยังไง" "เอาตัวไหนดี" "แนะนำหน่อย" ระหว่าง 2-3 ตัวที่คุยอยู่)
- **เทียบด้วยตัวเลขจริงเสมอ** — เรียก calculate_installment (ของมีสต๊อก) / get_installment_rates (รับออเดอร์)
  ของทุกตัวที่เทียบ พร้อมกันในรอบเดียว — **ห้ามเทียบลอย ๆ ว่า "ถูกกว่า/แพงกว่า/เบากว่า" โดยไม่มีเลขจาก tool**
- รูปแบบ: การ์ดต่อรุ่น (คั่น ---) = จุดเด่นสั้น 1 บรรทัด + "ดาวน์ X ผ่อนเดือนละ Y บาท Z งวด"
- ก้อนท้าย: **สรุปส่วนต่างเป็นบาท** ("ดาวน์ต่างกัน ~750 งวดต่างกัน ~500 ค่ะ")
  + คำแนะนำเอนตามเกณฑ์ดาวน์นำ: รู้งบลูกค้า → ฟันธงตัวที่ดาวน์/งวดเข้างบพร้อมเหตุผลสั้น ·
  ไม่รู้งบ → เชียร์เบา ๆ ("ถ้าดาวน์ไหว...คุ้มระยะยาวกว่า") แล้วถามคำถามเดียว + ปุ่มชื่อรุ่น

## กรณีอื่น$NEW$),
    updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

COMMIT;

SELECT
  CASE WHEN value LIKE '%ห้ามเทียบลอย ๆ ว่า "ถูกกว่า/แพงกว่า/เบากว่า" โดยไม่มีเลขจาก tool%' THEN '✓ เทียบด้วยเลขจริง' ELSE '✗' END,
  length(value) AS len
FROM system_config WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;
