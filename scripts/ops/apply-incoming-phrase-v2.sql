-- v2.7 (2026-08-14 คำสั่งเจ้าของ): คำพูดกับลูกค้าตอนสต๊อกว่าง "สั่งเข้าให้ได้" → "ของกำลังเข้ามา"
-- (ฟังดูของหมุนเวียนปกติ ไม่ใช่ต้องรอสั่งพิเศษ) — คำว่า "สั่งเข้า" ที่เป็น note ภายใน/กติกา คงไว้
BEGIN;

-- [1] กฎเหล็ก order-taking: ประโยคสต๊อกว่าง
UPDATE system_config
SET value = replace(value,
$OLD$  **ห้ามพูด "มี..." คู่กับ "สั่งเข้า" ในเรื่องเดียวกัน (ขัดกันเอง ลูกค้างง)** —
  สต๊อกว่างให้พูดตรง ๆ "ตอนนี้ของขาดพอดี สั่งเข้าให้ได้เลยค่ะ"$OLD$,
$NEW$  **ห้ามพูด "มีของ" คู่กับ "กำลังเข้ามา/สั่งเข้า" ในเรื่องเดียวกัน (ขัดกันเอง ลูกค้างง)** —
  สต๊อกว่างให้พูด "ตอนนี้ของกำลังเข้ามาค่ะ จองไว้ก่อนได้เลยนะคะ" (ห้ามใช้คำว่า "สั่งเข้า" กับลูกค้า)$NEW$),
    updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

-- [2] รายการมือ 1: ประโยคเดียวกันจุดที่สอง
UPDATE system_config
SET value = replace(value,
$OLD$  "ตอนนี้ของขาดพอดี สั่งเข้าให้ได้เลยค่ะ" (ห้ามพูด "มี" คู่กับ "สั่งเข้า")$OLD$,
$NEW$  "ตอนนี้ของกำลังเข้ามาค่ะ จองไว้ก่อนได้เลยนะคะ" (ห้ามพูด "มีของ" คู่กับ "กำลังเข้ามา" และห้ามใช้ "สั่งเข้า" กับลูกค้า)$NEW$),
    updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

-- [3] ตัวอย่างคำถามปิดท้าย: "สั่งเข้ามาให้ไหม" → จองล็อตที่กำลังเข้ามา
UPDATE system_config
SET value = replace(value,
$OLD$  → ปิดท้ายทั้งสองกรณีด้วยก้าวถัดไปของการรับออเดอร์ (คำถามเดียว เช่น "สนใจให้สั่งเข้ามาให้ไหมคะ") — **ห้ามจบด้วยความเงียบ**$OLD$,
$NEW$  → ปิดท้ายทั้งสองกรณีด้วยก้าวถัดไปของการรับออเดอร์ (คำถามเดียว เช่น "สนใจให้จองเครื่องที่กำลังเข้ามาไว้เลยไหมคะ") — **ห้ามจบด้วยความเงียบ**$NEW$),
    updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

COMMIT;

-- ตรวจผล
SELECT
  CASE WHEN value NOT LIKE '%สั่งเข้าให้ได้เลยค่ะ%' AND value NOT LIKE '%สั่งเข้ามาให้ไหมคะ%'
       THEN 'ลูกค้าไม่ได้ยิน "สั่งเข้า" ✓' ELSE '✗ ยังเหลือ' END,
  CASE WHEN value LIKE '%ของกำลังเข้ามาค่ะ จองไว้ก่อนได้เลยนะคะ%' THEN 'วลีใหม่ ✓' ELSE '✗' END,
  length(value) AS len
FROM system_config WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;
