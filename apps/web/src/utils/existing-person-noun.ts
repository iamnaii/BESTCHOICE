/**
 * คำเรียก "คนเดิม" เมื่อ POST /customers หรือเติมข้อมูลผู้สนใจชน 409 ข้อมูลซ้ำ
 * (คำตัดสิน 2026-09-17) ตามนิยามเจ้าของ 2026-09-12: ลูกค้า = ซื้อแล้ว ที่เหลือ = ผู้สนใจ
 *
 * ใช้ "ผู้สนใจ" เฉพาะเมื่อ API บอกชัดว่า `existingCustomer.purchased === false` —
 * ไม่บอก (API ก่อน M-A3) ⇒ "ลูกค้า" ตามเดิม · เว็บไม่เดาสถานะเอง
 *
 * ผู้ใช้: กล่องเบอร์ซ้ำของ `CustomerCreateDialog` + ข้อความ 409 ของ `useOcrFlow` (หน้าสร้างสัญญา)
 * — สองจอต้องเรียกคนเดิมด้วยกติกาเดียวกัน ห้ามเขียนเงื่อนไขนี้ซ้ำที่อื่น
 */
export function existingNounOf(purchased: boolean | undefined): 'ลูกค้า' | 'ผู้สนใจ' {
  return purchased === false ? 'ผู้สนใจ' : 'ลูกค้า';
}
