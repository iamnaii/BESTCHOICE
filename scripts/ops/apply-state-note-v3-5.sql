-- Idempotent: ข้ามถ้ามี section นี้อยู่แล้ว
BEGIN;

UPDATE system_config
SET value = value || $NEW$

## บันทึกสถานะลูกค้าจากระบบ (สมุดความจำ)
- ข้อความแรกของประวัติอาจเป็น "[บันทึกสถานะลูกค้าจากระบบ...]" — ระบบจดสถานะล่าสุดไว้ให้
  (รุ่นที่สนใจ งบดาวน์/งวด เรทที่เลือก เอกสาร ชื่อ-เบอร์ รุ่นที่เคยเสนอ เรื่องค้าง)
  ใช้เป็นบริบทได้เลย แต่**ห้ามเอ่ยถึงบันทึกนี้กับลูกค้าเด็ดขาด**
- **ห้ามถามซ้ำสิ่งที่มีในบันทึกแล้ว** — มีงบดาวน์แล้วก็ข้ามไปขั้นถัดไปของลำดับการขายเลย
- บันทึกมี "(คุยล่าสุดเมื่อ ... ก่อน)" = ลูกค้าเก่ากลับมา → **ทักต่อจากสถานะเดิม อย่าเริ่มนับหนึ่งใหม่**
  เช่น "สวัสดีค่ะพี่ 😊 เมื่อวานคุยเรื่อง iPhone 15 Plus 128GB ไว้ สนใจต่อเลยไหมคะ"
- บันทึกขัดกับข้อความล่าสุดของลูกค้า → เชื่อข้อความล่าสุดของลูกค้าเสมอ แล้วคุยตามนั้น
- บรรทัดประวัติที่เป็น "[รูป ...]" = รูปเครื่องที่เราส่งให้ลูกค้าแล้ว — ลูกค้าเห็นรูปนั้นอยู่
  อ้างถึงต่อได้เลย ไม่ต้องส่งซ้ำ ไม่ต้องถามว่าเห็นรูปไหม$NEW$,
    updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras'
  AND deleted_at IS NULL
  AND value NOT LIKE '%บันทึกสถานะลูกค้าจากระบบ (สมุดความจำ)%';

COMMIT;

SELECT
  CASE WHEN value LIKE '%บันทึกสถานะลูกค้าจากระบบ (สมุดความจำ)%' THEN '✓ v3.5 state-note' ELSE '✗' END AS state_note,
  CASE WHEN value LIKE '%ทักต่อจากสถานะเดิม อย่าเริ่มนับหนึ่งใหม่%' THEN '✓ returning-customer' ELSE '✗' END AS returning,
  length(value) AS len
FROM system_config WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;
