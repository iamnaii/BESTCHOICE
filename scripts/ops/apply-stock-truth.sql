-- กฎเหล็กข้อมูลสินค้า (2026-08-14 เทสจริง Nai: บอทลิสต์รุ่น 15 ทั้งตระกูล + ถามมือ 1
-- โดย tools_used = {} — 15 Plus ในระบบมี 0 เครื่อง, มือ 1 ทั้งร้านมีแค่ iPhone 16)
UPDATE system_config
SET value = replace(value,
$OLD$# ลำดับถามก่อนเสนอราคา (ต้องรู้ครบก่อนคิดเลขเสมอ)$OLD$,
$NEW$# กฎเหล็กข้อมูลสินค้า — ต้องเรียก search_products ก่อนพูดถึงสินค้าเสมอ
ชื่อรุ่น / ความจุ / สี / มือ 1-มือสอง / "มีของไหม" ทุกคำที่จะพิมพ์ถึง
ต้องมาจากผล search_products ของบทสนทนานี้เท่านั้น
- ยังไม่มีผล → เรียก search_products ก่อนเสมอ แม้แค่จะถามแยกรุ่น/ลิสต์ตัวเลือก
- ความจำของโมเดลเรื่อง "รุ่นที่มีในตลาด" = ห้ามใช้เด็ดขาด — ตลาดมีไม่ได้แปลว่าร้านมี
  (เช่น ร้านอาจไม่มี 15 Plus เลยสักเครื่อง และมือ 1 อาจมีแค่บางรุ่น)
- รุ่นที่ลูกค้าถามแล้วค้นไม่เจอในระบบ → ตอบเรทกลางจาก get_installment_rates
  ตามเดิม (ระบบจะปักธงให้พนักงานตามต่อเอง) ห้ามแต่งว่ามีของ

# ลำดับถามก่อนเสนอราคา (ต้องรู้ครบก่อนคิดเลขเสมอ)$NEW$),
    updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

SELECT CASE WHEN value LIKE '%กฎเหล็กข้อมูลสินค้า%' THEN 'UPDATED ✓' ELSE 'PATTERN ไม่เจอ' END
FROM system_config WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;
