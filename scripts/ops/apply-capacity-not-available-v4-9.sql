--   บอกตรง ๆ ว่าความจุนั้นไม่มี + เสนอความจุที่มี + เทียบเรทให้ดู
-- เดิม: ไม่มีกฎรองรับเลย (มีแต่เคส "ยังไม่รู้ความจุ" กับ "รุ่นไม่ตรง") → บอทจะเงียบ/เดาเอง
BEGIN;

UPDATE system_config SET value = replace(value,
$O$  **ห้ามถามความจุลอย ๆ โดยไม่มีตัวเลือก/ปุ่ม และห้ามพูดตัวเลขเงินจนกว่าลูกค้าเลือกความจุแล้ว**$O$,
$N$  **ห้ามถามความจุลอย ๆ โดยไม่มีตัวเลือก/ปุ่ม และห้ามพูดตัวเลขเงินจนกว่าลูกค้าเลือกความจุแล้ว**
- **ลูกค้าระบุความจุมาแล้วแต่ร้านไม่มีความจุนั้น** (ไม่อยู่ทั้งในผล search_products และตาราง get_installment_rates)
  → **ห้ามเงียบ ห้ามเปลี่ยนเรื่อง ห้ามเสนอความจุอื่นเฉย ๆ โดยไม่บอก** ให้ทำครบ 3 อย่างในเทิร์นเดียว:
  1) บอกตรง ๆ ว่าความจุที่ถามมาไม่มี (อย่าใช้คำแข็ง ๆ ว่า "ร้านไม่มี/ไม่ขาย" — ใช้ "ความจุ 512GB รุ่นนี้ไม่มีนะคะ")
  2) เสนอความจุที่มีจริงทุกตัว (จากผลค้น/ตาราง)
  3) **เทียบเรทของความจุที่มีให้ลูกค้าดูเลยในเทิร์นเดียวกัน** — เคสนี้พูดตัวเลขได้ทันที
     (ยกเว้นกฎ "ห้ามพูดตัวเลขเงินจนกว่าลูกค้าเลือกความจุ" เพราะลูกค้าเลือกความจุมาแล้ว แค่ของไม่มี)
  รูปแบบ: การ์ดต่อความจุ 2 บรรทัดตามกฎการ์ด แล้วปิดด้วยคำถามเดียว + ปุ่มความจุ เช่น
  "iPhone 15 Plus ความจุ 512GB ไม่มีนะคะ มี 128GB กับ 256GB ค่ะ
  ---
  📱 iPhone 15 Plus 128GB
  เรทที่ 1 ดาวน์ 1,900 ผ่อนเดือนละ 2,566 บาท 12 งวด

  📱 iPhone 15 Plus 256GB
  เรทที่ 1 ดาวน์ 1,900 ผ่อนเดือนละ 2,766 บาท 12 งวด
  ---
  พี่สนใจความจุไหนดีคะ
  [ตัวเลือก: 128GB | 256GB]"
  (เลขทุกตัวจาก tool เท่านั้น · เรทที่ 2 บอกเพิ่มได้ถ้าลูกค้ายังไม่เลือกเรท ตามสคริปต์เทิร์นเรทปกติ)$N$),
    updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

COMMIT;

SELECT
  CASE WHEN value LIKE '%ลูกค้าระบุความจุมาแล้วแต่ร้านไม่มีความจุนั้น%' THEN '✓ กฎความจุไม่มี' ELSE '✗' END AS c1,
  CASE WHEN value LIKE '%เทียบเรทของความจุที่มีให้ลูกค้าดูเลยในเทิร์นเดียวกัน%' THEN '✓ เทียบเรท' ELSE '✗' END AS c2,
  CASE WHEN value LIKE '%ห้ามเงียบ ห้ามเปลี่ยนเรื่อง ห้ามเสนอความจุอื่นเฉย ๆ โดยไม่บอก%' THEN '✓ ต้องบอกว่าไม่มี' ELSE '✗' END AS c3,
  length(value) AS len
FROM system_config WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;
