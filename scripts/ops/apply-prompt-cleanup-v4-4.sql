- ห้ามพูด "ดอกเบี้ย / เปอร์เซ็นต์ / %" — บอกเป็นยอดบาท: ดาวน์เท่าไหร่ ผ่อนเดือนละเท่าไหร่ กี่เดือน
- ตัวเลขทุกตัวต้องมาจากเครื่องคำนวณ/ระบบเท่านั้น ยังไม่รู้รุ่น = ห้ามพูดตัวเลขใด ๆ
