-- หลัก: แยก "ประเภทเครื่อง" (เป็นมือสองคัดสภาพ) ออกจาก "สถานะสต๊อก" (ขาดพอดี/มีของ)
-- ห้ามคำว่า "มี..." อยู่คู่กับ "สั่งเข้า" ในเรื่องเดียวกัน
BEGIN;

-- [1] กฎเหล็กข้อมูลสินค้า (โหมดรับออเดอร์)
UPDATE system_config
SET value = replace(value,
$OLD$  รุ่นนอกรายการ = สั่งได้เฉพาะมือสอง → บอกไปเลย "รุ่นนี้มีเป็นมือสองคัดสภาพค่า" ห้ามถามมือ 1**$OLD$,
$NEW$  รุ่นนอกรายการ = สั่งได้เฉพาะมือสอง → บอกประเภทว่า "รุ่นนี้เป็นเครื่องมือสองคัดสภาพนะคะ" ห้ามถามมือ 1**
  **ห้ามพูด "มี..." คู่กับ "สั่งเข้า" ในเรื่องเดียวกัน (ขัดกันเอง ลูกค้างง)** —
  สต๊อกว่างให้พูดตรง ๆ "ตอนนี้ของขาดพอดี สั่งเข้าให้ได้เลยค่ะ"$NEW$),
    updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

-- [2] รายการมือ 1 (กติการุ่นนอกรายการ)
UPDATE system_config
SET value = replace(value,
$OLD$  → บอกเลย "รุ่นนี้มีเป็นมือสองคัดสภาพค่า" แล้วเดินลำดับรับออเดอร์ต่อ (ความจุ → เรท → เก็บ lead)$OLD$,
$NEW$  → บอกประเภท "รุ่นนี้เป็นเครื่องมือสองคัดสภาพค่า" — สต๊อกว่างก็บอกตรง ๆ ต่อว่า
  "ตอนนี้ของขาดพอดี สั่งเข้าให้ได้เลยค่ะ" (ห้ามพูด "มี" คู่กับ "สั่งเข้า")
  แล้วเดินลำดับรับออเดอร์ต่อ (ความจุ → เรท → เก็บ lead)$NEW$),
    updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

COMMIT;

-- ตรวจผล: ต้อง ✓ ทั้ง 2 และวลีเดิมหมดเกลี้ยง
SELECT
  CASE WHEN value NOT LIKE '%มีเป็นมือสองคัดสภาพ%' THEN '[old] ✓ หมดเกลี้ยง' ELSE '[old] ✗ ยังเหลือ' END,
  CASE WHEN value LIKE '%ห้ามพูด "มี..." คู่กับ "สั่งเข้า"%' THEN '[1] ✓' ELSE '[1] ✗' END,
  CASE WHEN value LIKE '%ของขาดพอดี สั่งเข้าให้ได้เลยค่ะ%' THEN '[2] ✓' ELSE '[2] ✗' END,
  length(value) AS len
FROM system_config WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;
