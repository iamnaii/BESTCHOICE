-- ทำให้คำถามความจุในโหมดรับออเดอร์ (ค้นแล้วว่าง) ไม่มีแหล่งตัวเลือก → บอทเลิกแนบปุ่ม
-- แก้: เพิ่มแหล่งที่มาที่ยอมรับ (ตาราง get_installment_rates + รายการมือ 1 + ตัวเลือกตายตัว)
-- + บังคับแนบปุ่มเมื่อคำถามปิดท้ายมีตัวเลือกชัดเจน ≤6 ตัว
-- + อนุญาตเรียก get_installment_rates ล่วงหน้าเพื่อ "ดูตัวเลือก" ได้ (ห้ามพูดตัวเลขก่อนข้อมูลครบ)
BEGIN;

-- [1] ปุ่มกดตอบ: แหล่งที่มา + บังคับแนบ
UPDATE system_config
SET value = replace(value,
$OLD$- ใช้เมื่อไหร่: เลือกรุ่น (เอาชื่อจากผล search_products) · ความจุ · มือ 1/มือสอง ·
  แบบผ่อน (ตามเรทของรุ่นนั้น) · คำถามใช่-ไม่ใช่$OLD$,
$NEW$- ใช้เมื่อไหร่: เลือกรุ่น · ความจุ · มือ 1/มือสอง · แบบผ่อน/เรท · คำถามใช่-ไม่ใช่
  **คำถามปิดท้ายที่มีตัวเลือกชัดเจนไม่เกิน 6 ตัว = ต้องแนบปุ่มเสมอ อย่าปล่อยให้ลูกค้าพิมพ์เอง**
- แหล่งที่มาของตัวเลือก (ต้องมาจากที่ใดที่หนึ่งต่อไปนี้เท่านั้น ห้ามนึกรายชื่อเอง):
  ผล search_products · ชื่อรุ่น+ความจุจากผล get_installment_rates ·
  "รายการมือ 1 ที่ร้านขายตอนนี้" ในพรอมป์ตนี้ · ตัวเลือกตายตัว (มือ 1/มือสอง · ใช่/ไม่ใช่ · เรทร้าน/เรท GFIN)
  → โหมดรับออเดอร์จะถามความจุ: เรียก get_installment_rates ของรุ่นนั้นก่อนได้เลย
    เพื่อดูว่ามีความจุไหนในตาราง แล้วทำปุ่มจากความจุเหล่านั้น
    — **แต่ห้ามพูดตัวเลขเงินจนกว่าลูกค้าเลือกความจุแล้ว**
  → ไม่มีแหล่งใดให้อ้างเลย → ถามปลายเปิดโดยไม่แนบปุ่ม$NEW$),
    updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

-- [2] #1337: เปิดทางเรียก tool เพื่อ "ดูตัวเลือก" ก่อนข้อมูลครบ (ที่ห้ามคือบอกตัวเลข)
UPDATE system_config
SET value = replace(value,
$OLD$    ยังไม่ครบ → ถามต่อทีละข้อตาม "ลำดับถามก่อนเสนอราคา" ยังไม่บอกเรท$OLD$,
$NEW$    ยังไม่ครบ → ถามต่อทีละข้อตาม "ลำดับถามก่อนเสนอราคา" ยังไม่บอกเรท
    (เรียก get_installment_rates ล่วงหน้าเพื่อดูรุ่น/ความจุที่มีในตารางไว้ทำปุ่มตัวเลือกได้
    — แค่ห้ามพูดตัวเลขเงินก่อนข้อมูลครบ)$NEW$),
    updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

COMMIT;

-- ตรวจผล: ต้อง ✓ ทั้ง 3
SELECT
  CASE WHEN value LIKE '%ต้องแนบปุ่มเสมอ อย่าปล่อยให้ลูกค้าพิมพ์เอง%' THEN '[1] ✓ บังคับแนบปุ่ม' ELSE '[1] ✗' END,
  CASE WHEN value LIKE '%แหล่งที่มาของตัวเลือก%' THEN '[1] ✓ แหล่งปุ่ม' ELSE '[1] ✗' END,
  CASE WHEN value LIKE '%ไว้ทำปุ่มตัวเลือกได้%' THEN '[2] ✓ ดูตัวเลือกล่วงหน้า' ELSE '[2] ✗' END,
  length(value) AS len
FROM system_config WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;
