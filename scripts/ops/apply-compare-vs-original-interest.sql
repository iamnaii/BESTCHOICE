-- v3.4 (2026-08-15 คำสั่งเจ้าของ): "ต่างกันยังไง" โดยไม่ระบุคู่เทียบ
-- = เทียบตัวที่กำลังดูอยู่ กับ "รุ่นที่ลูกค้าสนใจ/ถามถึงตอนแรกในบทสนทนา" — ไม่ใช่ถามกลับ
BEGIN;

UPDATE system_config
SET value = replace(value,
$OLD$## ลูกค้าขอเทียบรุ่น ("ต่างกันยังไง" "เอาตัวไหนดี" "แนะนำหน่อย" ระหว่าง 2-3 ตัวที่คุยอยู่)$OLD$,
$NEW$## ลูกค้าขอเทียบรุ่น ("ต่างกันยังไง" "เอาตัวไหนดี" "แนะนำหน่อย" ระหว่าง 2-3 ตัวที่คุยอยู่)
- **"ต่างกันยังไง" โดยไม่ระบุคู่เทียบ = เทียบตัวที่กำลังดู/เพิ่งเสนอ กับรุ่นที่ลูกค้าสนใจหรือถามถึง
  ก่อนหน้าในบทสนทนา (ตัวที่เขาเปิดมาหาตั้งแต่แรกสำคัญสุด)** — ไล่ดูประวัติก่อนเสมอ
  ถามกลับ "เทียบกับรุ่นไหนคะ" ได้เฉพาะเมื่อทั้งบทสนทนามีรุ่นเดียวจริง ๆ$NEW$),
    updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

COMMIT;

SELECT
  CASE WHEN value LIKE '%ตัวที่เขาเปิดมาหาตั้งแต่แรกสำคัญสุด%' THEN '✓ เทียบกับความสนใจแรก' ELSE '✗' END,
  length(value) AS len
FROM system_config WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;
