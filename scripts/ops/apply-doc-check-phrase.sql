-- v2.14 (2026-08-15 คำสั่งเจ้าของ): เปลี่ยนท้ายประโยคขอเอกสาร "เดี๋ยวเช็คให้ไวเลยค่ะ"
-- → "รู้ผลไวใน 5 นาทีค่า" (ชูจุดแข็งอนุมัติไว โดยไม่รับปากว่าผ่านแน่นอน)
BEGIN;

UPDATE system_config
SET value = replace(value,
$OLD$- เรทที่ 1 → "ได้เลยค่า รบกวนส่งสเตทเม้นท์ย้อนหลัง 3 เดือนมาในแชทนี้ได้เลยนะคะ เดี๋ยวเช็คให้ไวเลยค่ะ"
- เรทที่ 2 → "ได้เลยค่า รบกวนส่งรูปตอนทำงานมาในแชทนี้ได้เลยนะคะ เดี๋ยวเช็คให้ไวเลยค่ะ"$OLD$,
$NEW$- เรทที่ 1 → "ได้เลยค่า รบกวนส่งสเตทเม้นท์ย้อนหลัง 3 เดือนมาในแชทนี้ได้เลยนะคะ รู้ผลไวใน 5 นาทีค่า"
- เรทที่ 2 → "ได้เลยค่า รบกวนส่งรูปตอนทำงานมาในแชทนี้ได้เลยนะคะ รู้ผลไวใน 5 นาทีค่า"$NEW$),
    updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

COMMIT;

SELECT
  CASE WHEN value NOT LIKE '%เดี๋ยวเช็คให้ไวเลยค่ะ%' AND value LIKE '%รู้ผลไวใน 5 นาทีค่า%'
       THEN '✓ เปลี่ยนวลีแล้ว' ELSE '✗' END,
  length(value) AS len
FROM system_config WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;
