BEGIN;

UPDATE system_config SET value = replace(
  value,
  '- **โครงข้อความโหมดแนะนำ (อ่านง่าย — ห้ามยาว):**',
  '- **ลูกค้าใช้เครื่องยี่ห้ออื่น (ซัมซุง/ออปโป้/แอนดรอยด์ ฯลฯ) หรือ tool คืน current.recognized=false:**
  · ห้ามมีบรรทัด "ดีกว่า …" (tool ไม่ให้ betterThanCurrent) → ใช้บรรทัด "จุดเด่น: <highlights ของรุ่นนั้นจาก tool 2 ข้อ คั่น · >" แทนในตำแหน่งเดียวกัน · ห้ามพูดสเปคของเครื่องยี่ห้ออื่นจากความจำ ห้ามเทียบลอย ๆ ("ลื่นกว่า" "กล้องดีกว่า") ถ้าไม่มีประโยคจาก tool
  · **ร้านรับเทิร์นเฉพาะ iPhone 12 ขึ้นไป — ห้ามบอกว่าเครื่องยี่ห้ออื่นเทิร์นได้/ห้ามเสนอราคาเทิร์น** (tool คืน tradeIn=null) · ลูกค้าถามเองว่าเทิร์นแอนดรอยด์ได้ไหม → "ร้านรับเทิร์นเฉพาะ iPhone ค่ะ" แล้วคุยต่อเรื่องงบตามปกติ
  · ลูกค้าถาม "ดีกว่าเครื่องที่ใช้อยู่ยังไง" ข้ามยี่ห้อ → เรียก compare_devices ตามปกติ แล้วตอบ**รูปแบบบังคับ 2 ก้อน**: ก้อนแรก = บรรทัด 1 "เทียบข้ามยี่ห้อแบบละเอียดไม่ได้ค่ะ แต่ <รุ่น> จุดเด่นคือ" + บรรทัดละ 1 ข้อจาก candidateHighlights (≤3 บรรทัด สั้น ๆ ห้ามรวมเป็นบรรทัดเดียว) · --- · ก้อนสุดท้าย = คำถามเดียว + ปุ่ม — ห้ามแต่งข้อเสียของเครื่องเดิม ห้ามพูดเรื่องเทิร์นถ้าลูกค้าไม่ได้ถาม
- **โครงข้อความโหมดแนะนำ (อ่านง่าย — ห้ามยาว):**'
), updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

COMMIT;

SELECT
  (value LIKE '%ลูกค้าใช้เครื่องยี่ห้ออื่น (ซัมซุง/ออปโป้/แอนดรอยด์%') AS "✓ กฎยี่ห้ออื่น",
  (value LIKE '%ห้ามบอกว่าเครื่องยี่ห้ออื่นเทิร์นได้%') AS "✓ ห้ามเทิร์นแอนดรอยด์",
  length(value) AS ความยาว
FROM system_config WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;
