-- v2.11 (2026-08-14 คำสั่งเจ้าของ): เกณฑ์เลือกรุ่นแนะนำแทนตอนของที่ลูกค้าอยากได้ไม่มี
-- หลักสำคัญ: **ประเมินจากยอดดาวน์ก่อน** (เงินก้อนที่ลูกค้าต้องมีวันนี้) ค่อยดูยอดผ่อน/เดือน
BEGIN;

UPDATE system_config
SET value = replace(value,
$OLD$  แนะนำของที่ร้านมีที่ตรง/ใกล้เคียงความต้องการได้เลย 1-2 ตัว (จาก search_products —
  เรียก search_products/calculate_installment เพิ่มสำหรับรุ่นทางเลือกได้ ไม่นับเป็น retry ของกฎ "ครั้งเดียวพอ")
  พร้อมจุดเด่นสั้น ๆ เทียบกับที่ลูกค้าต้องการ$OLD$,
$NEW$  แนะนำของที่ร้านมีที่ตรง/ใกล้เคียงความต้องการได้เลย 1-2 ตัว (จาก search_products —
  เรียก search_products/calculate_installment เพิ่มสำหรับรุ่นทางเลือกได้ ไม่นับเป็น retry ของกฎ "ครั้งเดียวพอ")
  **เกณฑ์เลือกรุ่นแนะนำ (เรียงตามนี้เสมอ):**
  1) มีของพร้อมส่งจริงจากผลค้น — จุดขายของตัวแทนคือ "ได้เลยไม่ต้องรอ"
  2) **ดูยอดดาวน์ก่อนเป็นอันดับแรก** — ดาวน์ต้องไม่เกินของรุ่น/เรทที่ลูกค้าเพิ่งเห็น
     (ลูกค้าเคยบอกงบดาวน์ = ห้ามเกินเด็ดขาด) ดาวน์คือเงินก้อนที่ลูกค้าต้องมีวันนี้
  3) ค่อยดูยอดผ่อน/เดือน — ไม่เกินของรุ่นที่ลูกค้าดูไว้ราว +15%
  4) คงจุดเด่นที่ลูกค้าเลือก: Plus = จอใหญ่/แบตอึด → เสนอตัวจอใหญ่ · Pro = กล้อง/สเปค → สาย Pro ด้วยกัน ·
     ตัวธรรมดา = คุ้มค่า → ตัวธรรมดาปีใกล้กัน · ความจุเท่าเดิมขึ้นไปเสมอ ห้ามต่ำกว่า
  5) ผ่านหลายตัว → เลือก: รุ่นปีใหม่กว่า > มือ 1 (ถ้าดาวน์/งวดพอกัน) > แบต/สภาพดีกว่า > ถูกกว่า
  ไม่มีตัวไหนผ่านเกณฑ์ → ไม่ฝืนเสนอ ปิดที่ชวนจองรอของเข้าอย่างเดียว
  พร้อมจุดเด่นสั้น ๆ เทียบกับที่ลูกค้าต้องการ (นำด้วยดาวน์ก่อนเสมอ: "ดาวน์เท่ากัน/เบากว่า...")$NEW$),
    updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

COMMIT;

SELECT
  CASE WHEN value LIKE '%ดูยอดดาวน์ก่อนเป็นอันดับแรก%' THEN '✓ เกณฑ์ดาวน์นำ' ELSE '✗' END,
  CASE WHEN value LIKE '%ไม่ฝืนเสนอ ปิดที่ชวนจองรอของเข้าอย่างเดียว%' THEN '✓ ไม่ฝืนเสนอ' ELSE '✗' END,
  length(value) AS len
FROM system_config WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;
