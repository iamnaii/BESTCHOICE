-- → ห้ามตอบแค่ "สนใจรุ่นไหนคะ" — ให้ถามงบดาวน์ก่อน แล้วงวดที่ไหว แล้วเสนอรุ่นในงบ (การ์ดสั้น)
BEGIN;

-- [1] กฎ "ยังไม่บอกรุ่น": จาก "ถามรุ่นก่อน" → แยกเคส
UPDATE system_config
SET value = replace(value,
$OLD$- ถ้าลูกค้ายังไม่บอกรุ่น (ยังไม่มีผล tool ให้อ้าง) → **ห้ามพูดตัวเลขบาทใด ๆ** แม้แต่ช่วงดาวน์คร่าว ๆ ของร้าน
  → ถามรุ่นก่อน: "สนใจรุ่นไหนอยู่คะ เดี๋ยวบอกดาวน์กับค่างวดให้เลยค่ะ" — ตอบเลขได้เมื่อ tool คืนผลแล้วเท่านั้น$OLD$,
$NEW$- ถ้าลูกค้ายังไม่บอกรุ่น (ยังไม่มีผล tool ให้อ้าง) → **ห้ามพูดตัวเลขบาทใด ๆ** แม้แต่ช่วงดาวน์คร่าว ๆ ของร้าน
  → ลูกค้าทักมาเฉย ๆ ยังไม่ถามราคา = ถามรุ่นก่อน ("สนใจรุ่นไหนอยู่คะ")
  → **ลูกค้าถามราคา/ดาวน์/ค่างวดแบบรวม ๆ หรือเลือกรุ่นไม่ถูก = ถามงบดาวน์ก่อนเสมอ**
    ("พี่มีงบดาวน์ประมาณเท่าไหร่คะ") → แล้วถามงวดที่ไหว → เสนอรุ่นในงบเป็นการ์ดสั้น
    (ดูหัวข้อ "ทำความรู้จักลูกค้า") — **ห้ามเด้งกลับแค่ "สนใจรุ่นไหนคะ" ในเคสนี้**
  ตอบเลขได้เมื่อ tool คืนผลแล้วเท่านั้น$NEW$),
    updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

-- [2] trigger ของหัวข้อทำความรู้จักลูกค้า: เพิ่มเคสถามราคาโดยไม่เลือกรุ่น
UPDATE system_config
SET value = replace(value,
$OLD$เมื่อลูกค้าไม่ได้ระบุรุ่น ("มีรุ่นไหนบ้าง" "แนะนำหน่อย" "งบสามพัน") หรือเลือกไม่ถูก
ให้ทำความรู้จักก่อนเสนอ — ถามทีละข้อ ไม่เกิน 3 ข้อ อย่าให้เหมือนสอบสวน:$OLD$,
$NEW$เมื่อลูกค้าไม่ได้ระบุรุ่น ("มีรุ่นไหนบ้าง" "แนะนำหน่อย" "งบสามพัน") หรือเลือกไม่ถูก
**หรือถามราคา/ดาวน์/ค่างวดแบบรวม ๆ โดยยังไม่เลือกรุ่น** (เช่น "ดาวน์เท่าไหร่" หลังเห็นลิสต์หลายรุ่น)
ให้ทำความรู้จักก่อนเสนอ — ถามทีละข้อ ไม่เกิน 3 ข้อ อย่าให้เหมือนสอบสวน
(ห้ามเด้งกลับ "สนใจรุ่นไหนคะ" — ลูกค้ากำลังเลือกไม่ถูก ถามงบช่วยเลือกได้ตรงกว่า):$NEW$),
    updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

COMMIT;

SELECT
  CASE WHEN value LIKE '%ลูกค้าถามราคา/ดาวน์/ค่างวดแบบรวม ๆ หรือเลือกรุ่นไม่ถูก = ถามงบดาวน์ก่อนเสมอ%' THEN '[1] ✓' ELSE '[1] ✗' END,
  CASE WHEN value LIKE '%หรือถามราคา/ดาวน์/ค่างวดแบบรวม ๆ โดยยังไม่เลือกรุ่น**%' THEN '[2] ✓' ELSE '[2] ✗' END,
  length(value) AS len
FROM system_config WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;
