-- v5.1 ห้ามชวนลูกค้าโอนเงิน/ส่ง QR ในแชท (คำสั่งเจ้าของ 2026-08-22)
-- เจอจากแชทจริง: บอทปิดท้ายว่า "ทีมงานจะติดต่อกลับ พร้อม QR ดาวน์ 3,200 บาทให้ในแชทนี้เลยค่ะ"
-- ต้นตอหลักคือ handoffMessage ในโค้ด (แก้แล้ว) — ข้อนี้กันบอทแต่งเรื่องโอนเงินขึ้นเอง
BEGIN;

UPDATE system_config SET value = replace(
  value,
  '- **lead จาก capture_lead คือทางเดียวที่ทีมจะเห็นออเดอร์ — ไม่มีระบบตามต่ออัตโนมัติ**',
  '- **lead จาก capture_lead คือทางเดียวที่ทีมจะเห็นออเดอร์ — ไม่มีระบบตามต่ออัตโนมัติ**
- **ห้ามชวนลูกค้าโอนเงินหรือพูดถึง QR/พร้อมเพย์/มัดจำ ในแชทเด็ดขาด** — ทุกกรณี ทุกขั้น รวมตอนปิดการขาย: ลูกค้าต้องผ่านตรวจเอกสารและเข้ามาดูเครื่องที่ร้านก่อนเสมอ แล้วค่อยจ่ายดาวน์ที่ร้าน · ปิดท้าย capture_lead ใช้ข้อความที่ tool คืนมาเท่านั้น ห้ามเติมเรื่องการจ่ายเงินเอง · ลูกค้าถามเองว่า "โอนยังไง/จ่ายดาวน์ยังไง" → "จ่ายที่ร้านตอนรับเครื่องได้เลยค่ะ ยังไม่ต้องโอนอะไรทั้งนั้นนะคะ"'
), updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

COMMIT;

SELECT
  (value LIKE '%ห้ามชวนลูกค้าโอนเงินหรือพูดถึง QR%') AS "✓ใส่กฎห้ามโอนแล้ว",
  (length(value) - 0) AS ความยาว
FROM system_config WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;
