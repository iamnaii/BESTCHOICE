-- ห้ามโชว์ราคาเต็มเครื่องนำ — เทียบตัวเลือก (เกรด/สภาพ/ความจุ) ด้วย "ดาวน์ + ผ่อนเดือนละ" เสมอ
BEGIN;

UPDATE system_config
SET value = replace(value,
$OLD$- บอกลูกค้าแค่ 3 อย่าง: ดาวน์กี่บาท ผ่อนเดือนละกี่บาท กี่งวด — เหมือนสติกเกอร์ติดหน้าร้านเป๊ะ ๆ$OLD$,
$NEW$- บอกลูกค้าแค่ 3 อย่าง: ดาวน์กี่บาท ผ่อนเดือนละกี่บาท กี่งวด — เหมือนสติกเกอร์ติดหน้าร้านเป๊ะ ๆ
- **ห้ามโชว์ราคาเต็มเครื่องนำ (เราคุยผ่อน ไม่ใช่ขายสด)** — เทียบตัวเลือกทุกแบบ
  (เกรด/สภาพ/ความจุ/มือ 1-มือสอง) ให้เทียบด้วย "ดาวน์ + ผ่อนเดือนละ" จาก calculate_installment
  (เรียกหลายเครื่องพร้อมกันได้ในรอบเดียว) เช่น "เกรด B แบต 87% ดาวน์ 1,750 ผ่อนเดือนละ 1,5xx ·
  เกรด A แบต 92% ดาวน์ 1,990 ผ่อนเดือนละ 1,7xx" — ราคาเต็มเครื่องเอ่ยได้เฉพาะเมื่อลูกค้า
  ถามราคาเต็ม/ขอซื้อสดเอง$NEW$),
    updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

COMMIT;

SELECT
  CASE WHEN value LIKE '%ห้ามโชว์ราคาเต็มเครื่องนำ%' THEN '✓ กฎห้ามราคาเต็มนำ' ELSE '✗' END,
  length(value) AS len
FROM system_config WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;
