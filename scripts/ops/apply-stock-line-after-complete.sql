-- v2.9 (2026-08-14 คำสั่งเจ้าของ): "ของกำลังเข้ามา จองไว้ก่อนได้" ห้ามพูดตอนกำลังถามข้อมูล
-- ให้ถามครบก่อน (ความจุ ฯลฯ) แล้วพูดประโยคนี้ในเทิร์นเดียวกับที่บอกเรท
-- ลำดับเต็ม: เหตุผลมือสอง (เลิกผลิต) → ถามความจุ → [ครบ] กำลังเข้ามา+เรท+ชวนจอง → เก็บ lead
BEGIN;

-- [1] กฎเหล็กข้อมูลสินค้า (โหมดรับออเดอร์)
UPDATE system_config
SET value = replace(value,
$OLD$  **ห้ามพูด "มีของ" คู่กับ "กำลังเข้ามา/สั่งเข้า" ในเรื่องเดียวกัน (ขัดกันเอง ลูกค้างง)** —
  สต๊อกว่างให้พูด "ตอนนี้ของกำลังเข้ามาค่ะ จองไว้ก่อนได้เลยนะคะ" (ห้ามใช้คำว่า "สั่งเข้า" กับลูกค้า)$OLD$,
$NEW$  **ห้ามพูด "มีของ" คู่กับ "กำลังเข้ามา/สั่งเข้า" ในเรื่องเดียวกัน (ขัดกันเอง ลูกค้างง)** —
  สต๊อกว่าง: **ตอนที่ยังถามข้อมูลอยู่ ห้ามพูดเรื่องสต๊อก** — ถามให้ครบก่อน
  พอครบแล้ว ค่อยพูด "ตอนนี้ของกำลังเข้ามาค่ะ จองไว้ก่อนได้เลยนะคะ" ในเทิร์นเดียวกับที่บอกเรท
  (ห้ามใช้คำว่า "สั่งเข้า" กับลูกค้า)$NEW$),
    updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

-- [2] รายการมือ 1 (กติการุ่นนอกรายการ)
UPDATE system_config
SET value = replace(value,
$OLD$  → บอกเหตุผลด้วยเสมอ: "รุ่นนี้มือ 1 ไม่มีผลิตแล้วนะคะ จะเป็นเครื่องมือสองคัดสภาพค่า"
  — สต๊อกว่างก็บอกตรง ๆ ต่อว่า
  "ตอนนี้ของกำลังเข้ามาค่ะ จองไว้ก่อนได้เลยนะคะ" (ห้ามพูด "มีของ" คู่กับ "กำลังเข้ามา" และห้ามใช้ "สั่งเข้า" กับลูกค้า)
  แล้วเดินลำดับรับออเดอร์ต่อ (ความจุ → เรท → เก็บ lead)$OLD$,
$NEW$  → บอกเหตุผลด้วยเสมอ: "รุ่นนี้มือ 1 ไม่มีผลิตแล้วนะคะ จะเป็นเครื่องมือสองคัดสภาพค่า"
  แล้ว**ถามต่อให้ครบก่อน** (ความจุ ฯลฯ) — เรื่องสต๊อก/การจองยังไม่พูดในจังหวะนี้
  พอข้อมูลครบ เทิร์นที่บอกเรทค่อยเปิดด้วย "ตอนนี้ของกำลังเข้ามาค่ะ จองไว้ก่อนได้เลยนะคะ"
  (ห้ามพูด "มีของ" คู่กับ "กำลังเข้ามา" และห้ามใช้ "สั่งเข้า" กับลูกค้า)
  ลำดับเต็ม: เหตุผลมือสอง → ความจุ → [ครบ] กำลังเข้ามา + เรท + ชวนจอง → เก็บ lead$NEW$),
    updated_at = NOW()
WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;

COMMIT;

-- ตรวจผล
SELECT
  CASE WHEN value LIKE '%ตอนที่ยังถามข้อมูลอยู่ ห้ามพูดเรื่องสต๊อก%' THEN '[1] ✓' ELSE '[1] ✗' END,
  CASE WHEN value LIKE '%เทิร์นที่บอกเรทค่อยเปิดด้วย%' THEN '[2] ✓' ELSE '[2] ✗' END,
  length(value) AS len
FROM system_config WHERE key = 'shop_bot_persona_bot_extras' AND deleted_at IS NULL;
