export function getMenuIcon(path: string, fallback: NavigationIcon): NavigationIcon {
  if (path === '/collections') return MENU_ICONS['/overdue'];
  if (path === '/settings') return MENU_GROUP_ICONS['settings:ตั้งค่าระบบ'];
  return MENU_ICONS[path] ?? fallback;
}
