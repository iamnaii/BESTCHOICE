import { Prisma } from '@prisma/client';

/**
 * รหัสบัญชีสำหรับการขายผ่านบริษัทไฟแนนซ์ภายนอก (C1)
 *
 * ## สถานะ: **เปิดใช้แล้ว — คำตัดสินเจ้าของ 2026-08-26 ("ทำให้ลงได้เลย")**
 *
 * ผู้สอบตอบเรื่อง C1 ว่า *"แก้ไปข้างหน้าเหมือนกัน"* แต่ **ไม่ได้ระบุรหัสบัญชี** และ
 * คำถามรอบ 3 ข้อ 2 (ที่เสนอ `S11-3101`/`S51-1106`) **ยังไม่ได้รับคำตอบ**
 *
 * เจ้าของสั่งให้เดินหน้าด้วยรหัสที่เราเสนอไปก่อน ⇒ **สองรหัสนี้เป็นข้อเสนอของเรา
 * ไม่ใช่คำวินิจฉัยผู้สอบ** ถ้าผู้สอบตอบกลับมาเป็นรหัสอื่น ต้องแก้ค่าคงที่สองตัวนี้
 * + ย้ายรายการที่ลงไปแล้ว (ไม่ใช่แค่แก้โค้ด) — บันทึกไว้ที่
 * `docs/accounting/cpa-questions-round3-final-2026-08-25.txt` ข้อ 2
 *
 * เหตุผลที่รหัสเป็นแบบนี้ (เผื่อผู้สอบถาม):
 *   - เปิดกลุ่มใหม่ `S11-31XX ลูกหนี้ภายนอก` แทนที่จะยัดเข้า `S11-30XX`
 *     เพราะกลุ่มหลังถูกเลนส์กระทบยอดระหว่างกิจการอ่าน **รายสัญญา**
 *   - `S51-1106` เป็นช่องถัดไปของกลุ่มค่าใช้จ่ายในการขาย (ต่อจาก S51-1105)
 *
 * **ห้ามเปลี่ยนไปใช้บัญชีที่มีอยู่แล้วเพื่อให้มันทำงานได้เร็วขึ้น** — โดยเฉพาะ
 * `S11-3001`/`S11-3002` ซึ่งถูกอ่านโดยเลนส์กระทบยอดระหว่างกิจการ **รายสัญญา**
 * ยอดที่ไม่มีเลขสัญญาจะกลายเป็น finding `ACCOUNT_DRIFT` ทุกเดือนตลอดไป
 * (ดู `.claude/rules/accounting.md` หัวข้อ "⛔ ห้ามลง JV มือในบัญชีที่เลนส์ inter-co อ่านต่อสัญญา")
 */
export const EXTERNAL_FINANCE_RECEIVABLE_CODE = 'S11-3101';

/** ค่าธรรมเนียมที่บริษัทไฟแนนซ์หักก่อนโอน — ดูหมายเหตุด้านบน */
export const EXTERNAL_FINANCE_FEE_CODE = 'S51-1106';

/**
 * บัญชีทั้งสองตัวมีอยู่ในผังจริงแล้วหรือยัง
 *
 * ใช้เป็น **ด่านเปิด/ปิดฟีเจอร์** แทน feature flag — เพราะเงื่อนไขที่แท้จริงคือ
 * "ผังพร้อมหรือยัง" ไม่ใช่ "อยากเปิดหรือยัง" ⇒ ผูกกับความจริงในฐานข้อมูลตรง ๆ
 * ไม่มีสวิตช์ให้ลืมเปิด และไม่มีทางเปิดก่อนผังพร้อม
 *
 * คืน `false` = ยังไม่ได้ `seed:coa` บนสภาพแวดล้อมนั้น (เช่น prod ที่ยังไม่ได้รัน)
 * ⇒ ระบบข้ามการโพสต์เงียบ ๆ แทนที่จะล้ม — การขาย/รับเงินต้องไม่พังเพราะผังยังไม่พร้อม
 */
export async function externalFinanceAccountsReady(
  tx: Prisma.TransactionClient,
): Promise<boolean> {
  const found = await tx.chartOfAccount.findMany({
    where: {
      code: { in: [EXTERNAL_FINANCE_RECEIVABLE_CODE, EXTERNAL_FINANCE_FEE_CODE] },
      status: 'ใช้งาน',
      deletedAt: null,
    },
    select: { code: true },
  });
  return found.length === 2;
}
